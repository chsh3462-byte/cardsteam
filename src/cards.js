// Categories have different jobs; compare stat efficiency within each category.
export function cardStatScore(c){
 const utility={thorns:2,guard:3,haste:4,bulwark:3,drain:4,echo:3,pierce:4,mend:2,freeze:4,gift:3,scorch:3,disrupt:4,siphon:3,rebirth:5,focus:2};
 const ease={even:1,odd:1,high:.7,six:.35,pair:.55};
 let strength;
 if(c.category==='unit')strength=c.basePower*3.5+c.hp*.6+(utility[c.effectType]||2)*(ease[c.overclock]+.5);
 else if(c.category==='tactic')strength=c.value*3.5*({sweep:2.5,chill:1.2,weaken:1.25,dispel:1.3,recall:1.3,tune:1.25}[c.effectType]||1)+({recall:8,tune:5,bolt:2}[c.effectType]||0);
 else if(c.category==='artifact')strength=c.value*({floor:12,raise:8,reroll:9,twin:8,guardgear:9,regengear:10,invert:6,reclaim:10,potion:3.5,mana:8,salvage:7,cleanse:5}[c.effectType]||5)+(c.equipment?8:0);
 else strength=(c.value*({steal:7,barrier:3.5,mend:3.5,smite:3.5,insight:9,jam:6,focus:8,tax:6,revive:7,nova:8}[c.effectType]||4)+4)*({enemySix:.6,ownPair:.9,ownSum18:.5,ownEven3:.5,enemyOdd3:.5,ownSum10:.98,enemyPair:.9,ownSix:.6,ownDistinct:.09}[c.trigger]||.5);
 return Math.round(strength/(1+c.cost*.22)*100)/100;
}
for(const category of ['unit','tactic','artifact','oracle']){
 const ranked=CARD_DATABASE.filter(c=>c.category===category).sort((a,b)=>cardStatScore(a)-cardStatScore(b));
 const sr=cardStatScore(ranked[Math.floor(ranked.length*.6)]),ssr=cardStatScore(ranked[Math.floor(ranked.length*.9)]);
 for(const c of ranked){c.statScore=cardStatScore(c);c.rarity=c.statScore>=ssr?'SSR':c.statScore>=sr?'SR':'R';}
}
